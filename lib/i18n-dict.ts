/** Remplace les noms de mois français dans un texte (dates affichées). */
export function traduireMois(s: string, lang: "en" | "ar"): string {
  let out = s;
  MOIS_FR_ABR.forEach((m, i) => {
    if (m.endsWith(".")) out = out.split(m).join(lang === "en" ? MOIS_ABR_EN[i] : MOIS.ar[i]);
  });
  MOIS_FR.forEach((m, i) => {
    out = out.replace(new RegExp(`(^|[\\s\\d])${m}(?=$|[\\s\\d.,])`, "gi"), (_x, p) => p + MOIS[lang][i]);
  });
  return out;
}

